-- ---------- Colonnes techniques communes : trigger d'horodatage / version ----------
create or replace function public.ck_touch() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  if tg_op = 'INSERT' then
    new.created_at := coalesce(new.created_at, now());
    new.updated_at := clock_timestamp();
    new.version := 1;
  else
    new.id := old.id;
    new.user_id := old.user_id;          -- une ligne ne change jamais de propriétaire
    new.created_at := old.created_at;
    new.seq := old.seq;
    new.updated_at := clock_timestamp();
    new.version := old.version + 1;
  end if;
  return new;
end $$;

-- ---------- Journal de toutes les modifications ----------
create table if not exists public.change_log (
  id bigint generated always as identity primary key,
  user_id uuid not null,
  tbl text not null,
  row_id uuid not null,
  action text not null,           -- insert | update | delete | restore
  old_row jsonb,
  new_row jsonb,
  device text,
  at timestamptz not null default now()
);
create index if not exists change_log_user_at on public.change_log (user_id, at desc);
create index if not exists change_log_row on public.change_log (row_id);

create or replace function public.ck_log() returns trigger
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_action text;
begin
  if tg_op = 'INSERT' then v_action := 'insert';
  elsif old.deleted_at is null and new.deleted_at is not null then v_action := 'delete';
  elsif old.deleted_at is not null and new.deleted_at is null then v_action := 'restore';
  else v_action := 'update';
  end if;
  insert into public.change_log (user_id, tbl, row_id, action, old_row, new_row, device)
  values (new.user_id, tg_table_name, new.id, v_action,
          case when tg_op = 'UPDATE' then to_jsonb(old) end, to_jsonb(new),
          nullif(current_setting('cockpit.device', true), ''));
  return null;
end $$;

-- ---------- Tables métier ----------
-- Macro : colonnes techniques identiques partout
--   id uuid (créé par l'appareil), user_id, seq (n° lisible), legacy_id (ID Excel d'origine),
--   created_at, updated_at, version (détection des conflits), deleted_at (suppression logique)

create table if not exists public.tx (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  seq bigint generated by default as identity, legacy_id integer,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  version integer not null default 1, deleted_at timestamptz,
  date date not null,
  activite text not null check (activite in ('Perso', 'Freelance', 'Immobilier')),
  sens text not null check (sens in ('Revenu', 'Dépense')),
  categorie text not null,
  detail text not null default '',
  libelle text not null default '',
  montant numeric(14, 2) not null check (montant > 0),
  devise text not null default 'EUR' check (devise in ('EUR', 'MAD')),
  taux numeric(12, 6) not null default 1,
  montant_eur numeric(14, 2) not null default 0,
  nature text not null default 'Courant' check (nature in ('Courant', 'Investissement', 'Financement')),
  tiers text not null default '',
  lot text not null default '',
  periode text not null default '',
  ref text not null default '',
  note text not null default ''
);

