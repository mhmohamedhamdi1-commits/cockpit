-- ---------- Index, unicité anti-doublons ----------
create unique index if not exists tx_ref_uq on public.tx (user_id, ref) where ref <> '' and deleted_at is null;
create unique index if not exists categories_key_uq on public.categories (user_id, activite, sens, categorie);
create unique index if not exists params_key_uq on public.params (user_id, cle);
create unique index if not exists invoices_num_uq on public.invoices (user_id, numero) where numero <> '' and deleted_at is null;
create unique index if not exists lots_nom_uq on public.lots (user_id, nom) where deleted_at is null;
create unique index if not exists clients_nom_uq on public.clients (user_id, nom) where deleted_at is null;
create unique index if not exists accounts_nom_uq on public.accounts (user_id, nom) where deleted_at is null;

do $$
declare t text;
begin
  foreach t in array array['tx','categories','lots','tenants','clients','invoices','recurring','accounts','snapshots','params','rappels'] loop
    execute format('create index if not exists %I on public.%I (user_id, updated_at)', t || '_sync', t);
    execute format('drop trigger if exists ck_touch on public.%I', t);
    execute format('create trigger ck_touch before insert or update on public.%I for each row execute function public.ck_touch()', t);
    execute format('drop trigger if exists ck_log on public.%I', t);
    execute format('create trigger ck_log after insert or update on public.%I for each row execute function public.ck_log()', t);
  end loop;
end $$;

-- ---------- Notifications ----------
create table if not exists public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  label text not null default '',
  created_at timestamptz not null default now(),
  last_ok_at timestamptz,
  fail_count integer not null default 0
);

create table if not exists public.notif_log (
  user_id uuid not null references auth.users(id) on delete cascade,
  key text not null,
  sent_at timestamptz not null default now(),
  title text, body text,
  primary key (user_id, key)
);

-- ---------- Points de restauration (instantanés complets en base) ----------
create table if not exists public.restore_points (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  label text not null,
  created_at timestamptz not null default now(),
  rows integer not null default 0,
  data jsonb not null
);
create index if not exists restore_points_user on public.restore_points (user_id, created_at desc);

-- ---------- Sécurité : RLS ----------
do $$
declare t text;
begin
  foreach t in array array['tx','categories','lots','tenants','clients','invoices','recurring','accounts','snapshots','params','rappels','push_subscriptions'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists own on public.%I', t);
    execute format('create policy own on public.%I for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))', t);
    execute format('drop policy if exists mfa on public.%I', t);
    execute format('create policy mfa on public.%I as restrictive for all to authenticated using ((select auth.jwt() ->> ''aal'') = ''aal2'') with check ((select auth.jwt() ->> ''aal'') = ''aal2'')', t);
    execute format('revoke all on public.%I from anon, public', t);
    -- lecture seule : toute écriture passe par apply_ops() (règles métier, contrôle de version)
    execute format('grant select on public.%I to authenticated', t);
  end loop;
end $$;
grant insert, update, delete on public.push_subscriptions to authenticated;

alter table public.change_log enable row level security;
alter table public.notif_log enable row level security;
alter table public.restore_points enable row level security;
drop policy if exists own_read on public.change_log;
create policy own_read on public.change_log for select to authenticated
  using (user_id = (select auth.uid()) and (select auth.jwt() ->> 'aal') = 'aal2');
drop policy if exists own_read on public.notif_log;
create policy own_read on public.notif_log for select to authenticated
  using (user_id = (select auth.uid()) and (select auth.jwt() ->> 'aal') = 'aal2');
drop policy if exists own_read on public.restore_points;
create policy own_read on public.restore_points for select to authenticated
  using (user_id = (select auth.uid()) and (select auth.jwt() ->> 'aal') = 'aal2');
revoke all on public.change_log, public.notif_log, public.restore_points from anon, public;
grant select on public.change_log, public.notif_log to authenticated;
grant select (id, user_id, label, created_at, rows) on public.restore_points to authenticated;
