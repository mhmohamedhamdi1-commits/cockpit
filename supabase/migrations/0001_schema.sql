-- Cockpit — schéma de la base centrale (Supabase / PostgreSQL)
-- Une table par ancien onglet Excel + rappels, abonnements push, journal, points de restauration.
-- Sécurité : RLS (propriétaire + MFA obligatoire) sur toutes les tables.
