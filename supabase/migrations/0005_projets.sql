-- =====================================================================================
-- Cockpit — projets immobiliers partagés
-- Immobilier -> Projet (ex. « Amal 1 ») -> lots -> locataires / opérations.
-- Un projet appartient à son propriétaire ; il peut inviter des personnes en LECTURE SEULE
-- (lien secret à usage unique). Un invité ne voit QUE les projets auxquels il est invité.
-- =====================================================================================

create table if not exists public.projets (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  seq bigint generated by default as identity, legacy_id integer,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  version integer not null default 1, deleted_at timestamptz,
  nom text not null,
  type text not null default 'Immobilier',
  part numeric(6, 4) not null default 1 check (part >= 0 and part <= 1),   -- part du propriétaire
  devise text not null default 'MAD',
  note text not null default ''
);
create index if not exists projets_sync on public.projets (user_id, updated_at);
drop trigger if exists ck_touch on public.projets;
create trigger ck_touch before insert or update on public.projets for each row execute function public.ck_touch();
drop trigger if exists ck_log on public.projets;
create trigger ck_log after insert or update on public.projets for each row execute function public.ck_log();

alter table public.lots add column if not exists projet_id uuid;
alter table public.tenants add column if not exists projet_id uuid;
alter table public.tx add column if not exists projet_id uuid;
alter table public.recurring add column if not exists projet_id uuid;
create index if not exists lots_projet on public.lots (projet_id) where projet_id is not null;
create index if not exists tenants_projet on public.tenants (projet_id) where projet_id is not null;
create index if not exists tx_projet on public.tx (projet_id) where projet_id is not null;
create index if not exists recurring_projet on public.recurring (projet_id) where projet_id is not null;

-- Membres invités
create table if not exists public.projet_membres (
  id uuid primary key default gen_random_uuid(),
  projet_id uuid not null references public.projets(id) on delete cascade,
  owner_id uuid not null references auth.users(id) on delete cascade,
  owner_email text not null default '',
  user_id uuid references auth.users(id) on delete cascade,          -- null tant que l'invitation n'est pas acceptée
  label text not null default '',                                     -- ex. « Fatima (sœur) »
  role text not null default 'lecteur' check (role in ('lecteur')),
  part numeric(6, 4) not null default 0 check (part >= 0 and part <= 1),
  token_hash text,
  expires_at timestamptz,
  status text not null default 'invite' check (status in ('invite', 'actif')),
  created_at timestamptz not null default now(),
  accepted_at timestamptz,
  updated_at timestamptz not null default now()
);
create unique index if not exists projet_membres_uq on public.projet_membres (projet_id, user_id) where user_id is not null;
create index if not exists projet_membres_user on public.projet_membres (user_id);

-- Droit de lecture d'une ligne partagée : membre actif du projet ET la ligne appartient bien au propriétaire du projet
create or replace function public.ck_can_view(p_projet uuid, p_row_owner uuid) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select p_projet is not null and exists (
    select 1 from public.projet_membres m join public.projets p on p.id = m.projet_id
    where m.projet_id = p_projet and m.user_id = (select auth.uid()) and m.status = 'actif'
      and p.user_id = p_row_owner and p.deleted_at is null)
$$;

-- ---------- Sécurité ----------
alter table public.projets enable row level security;
alter table public.projet_membres enable row level security;
drop policy if exists own on public.projets;
create policy own on public.projets for select to authenticated using (user_id = (select auth.uid()) or public.ck_can_view(id, user_id));
drop policy if exists mfa on public.projets;
create policy mfa on public.projets as restrictive for all to authenticated using ((select auth.jwt() ->> 'aal') = 'aal2');
do $$
declare t text;
begin
  foreach t in array array['lots', 'tenants', 'tx', 'recurring'] loop
    execute format('drop policy if exists shared on public.%I', t);
    execute format('create policy shared on public.%I for select to authenticated using (public.ck_can_view(projet_id, user_id))', t);
  end loop;
end $$;
drop policy if exists own on public.projet_membres;
create policy own on public.projet_membres for select to authenticated using (owner_id = (select auth.uid()) or user_id = (select auth.uid()));
drop policy if exists mfa on public.projet_membres;
create policy mfa on public.projet_membres as restrictive for all to authenticated using ((select auth.jwt() ->> 'aal') = 'aal2');
revoke all on public.projets, public.projet_membres from anon, public;
grant select on public.projets to authenticated;
grant select (id, projet_id, owner_id, owner_email, user_id, label, role, part, expires_at, status, created_at, accepted_at, updated_at) on public.projet_membres to authenticated;

-- ---------- Règles : un projet_id doit appartenir à l'auteur ; déduction depuis le lot ----------
create or replace function public.ck_fix_projet(p_uid uuid, p_tbl text, j jsonb) returns jsonb
language plpgsql stable set search_path = public, pg_temp as $$
declare v uuid;
begin
  if p_tbl = 'projets' then
    if btrim(coalesce(j ->> 'nom', '')) = '' then perform public.ck_err('nom du projet obligatoire'); end if;
    return j || jsonb_build_object('nom', btrim(j ->> 'nom'), 'part', least(1, greatest(0, coalesce(public.ck_num(j ->> 'part'), 1))),
      'devise', case when j ->> 'devise' = 'EUR' then 'EUR' else 'MAD' end);
  end if;
  if p_tbl not in ('lots', 'tenants', 'tx', 'recurring') then return j; end if;
  v := public.ck_uuid(j ->> 'projet_id');
  if v is null and p_tbl in ('tenants', 'tx', 'recurring') and coalesce(j ->> 'lot', '') <> '' and (p_tbl = 'tenants' or j ->> 'activite' = 'Immobilier') then
    select projet_id into v from public.lots where user_id = p_uid and nom = j ->> 'lot' and deleted_at is null limit 1;
  end if;
  if v is not null and not exists (select 1 from public.projets where id = v and user_id = p_uid and deleted_at is null) then
    perform public.ck_err('projet introuvable ou accessible en lecture seule');
  end if;
  if p_tbl = 'tx' and j ->> 'activite' <> 'Immobilier' then v := null; end if;
  return j || jsonb_build_object('projet_id', v);
end $$;

-- ---------- Invitations ----------
-- Crée une invitation en lecture seule et renvoie le code secret (à transmettre à la personne invitée)
create or replace function public.invite_to_projet(p_projet uuid, p_label text, p_part numeric) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_uid uuid := public.ck_require_aal2(); v_code text; v_id uuid;
begin
  if not exists (select 1 from public.projets where id = p_projet and user_id = v_uid and deleted_at is null) then
    perform public.ck_err('projet introuvable');
  end if;
  if (select count(*) from public.projet_membres where projet_id = p_projet) >= 20 then perform public.ck_err('20 invités maximum par projet'); end if;
  v_code := replace(gen_random_uuid()::text, '-', '') || replace(gen_random_uuid()::text, '-', '');
  insert into public.projet_membres (projet_id, owner_id, owner_email, label, role, part, token_hash, expires_at, status)
  values (p_projet, v_uid, coalesce(auth.jwt() ->> 'email', ''), left(btrim(coalesce(p_label, '')), 60), 'lecteur',
          least(1, greatest(0, coalesce(p_part, 0))), encode(sha256(convert_to(v_code, 'UTF8')), 'hex'), now() + interval '14 days', 'invite')
  returning id into v_id;
  return jsonb_build_object('id', v_id, 'code', v_code, 'expires_at', now() + interval '14 days');
end $$;

-- Accepte une invitation (l'utilisateur connecté devient membre en lecture seule). Code à usage unique.
create or replace function public.accept_invitation(p_code text) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_uid uuid := public.ck_require_aal2(); m public.projet_membres; v_nom text;
begin
  select * into m from public.projet_membres
   where token_hash = encode(sha256(convert_to(coalesce(p_code, ''), 'UTF8')), 'hex') and status = 'invite' for update;
  if m.id is null then perform public.ck_err('invitation invalide ou déjà utilisée'); end if;
  if m.expires_at < now() then perform public.ck_err('invitation expirée : demande un nouveau lien'); end if;
  if m.owner_id = v_uid then perform public.ck_err('tu es déjà propriétaire de ce projet'); end if;
  if exists (select 1 from public.projet_membres where projet_id = m.projet_id and user_id = v_uid) then
    delete from public.projet_membres where id = m.id;
    perform public.ck_err('tu as déjà accès à ce projet');
  end if;
  update public.projet_membres set user_id = v_uid, status = 'actif', token_hash = null, accepted_at = now(), updated_at = now() where id = m.id;
  select nom into v_nom from public.projets where id = m.projet_id;
  return jsonb_build_object('ok', true, 'projet', v_nom, 'projet_id', m.projet_id);
end $$;

-- Le propriétaire modifie (part, nom affiché) ou retire un membre / une invitation
create or replace function public.update_membre(p_id uuid, p_label text, p_part numeric) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_uid uuid := public.ck_require_aal2();
begin
  update public.projet_membres set label = left(btrim(coalesce(p_label, label)), 60), part = least(1, greatest(0, coalesce(p_part, part))), updated_at = now()
   where id = p_id and owner_id = v_uid;
  if not found then perform public.ck_err('membre introuvable'); end if;
  return jsonb_build_object('ok', true);
end $$;
create or replace function public.remove_membre(p_id uuid) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_uid uuid := public.ck_require_aal2();
begin
  delete from public.projet_membres where id = p_id and (owner_id = v_uid or user_id = v_uid);   -- le propriétaire retire, l'invité peut partir
  if not found then perform public.ck_err('membre introuvable'); end if;
  return jsonb_build_object('ok', true);
end $$;

revoke execute on function public.ck_can_view(uuid, uuid), public.ck_fix_projet(uuid, text, jsonb) from public, anon;
grant execute on function public.ck_can_view(uuid, uuid) to authenticated;   -- utilisée par la RLS
grant execute on function public.invite_to_projet(uuid, text, numeric), public.accept_invitation(text), public.update_membre(uuid, text, numeric), public.remove_membre(uuid) to authenticated;
