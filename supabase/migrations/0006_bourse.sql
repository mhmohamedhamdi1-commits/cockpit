-- =====================================================================================
-- Cockpit — module Bourse : ordres (achats, ventes, dividendes) par utilisateur ;
-- cours et historiques communs (données de marché publiques, non personnelles).
-- Le portefeuille est volontairement séparé des totaux (tableau de bord, trésorerie).
-- =====================================================================================
create table if not exists public.ordres (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  seq bigint generated by default as identity, legacy_id integer,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  version integer not null default 1, deleted_at timestamptz,
  date date not null,
  symbole text not null,
  nom text not null default '',
  type text not null default 'Action' check (type in ('Action', 'ETF', 'Fonds', 'Obligation', 'Crypto', 'Autre')),
  compte text not null default 'CTO',
  sens text not null check (sens in ('Achat', 'Vente', 'Dividende')),
  quantite numeric(20, 8) not null default 0,
  prix numeric(20, 8) not null default 0,
  frais numeric(14, 2) not null default 0,
  devise text not null default 'EUR',
  note text not null default ''
);
create index if not exists ordres_sync on public.ordres (user_id, updated_at);
drop trigger if exists ck_touch on public.ordres;
create trigger ck_touch before insert or update on public.ordres for each row execute function public.ck_touch();
drop trigger if exists ck_log on public.ordres;
create trigger ck_log after insert or update on public.ordres for each row execute function public.ck_log();
alter table public.ordres enable row level security;
drop policy if exists own on public.ordres;
create policy own on public.ordres for select to authenticated using (user_id = (select auth.uid()));
drop policy if exists mfa on public.ordres;
create policy mfa on public.ordres as restrictive for all to authenticated using ((select auth.jwt() ->> 'aal') = 'aal2');
revoke all on public.ordres from anon, public;
grant select on public.ordres to authenticated;

-- Cours (dernier connu) et historiques hebdomadaires : écrits par la fonction serveur « bourse »
create table if not exists public.cours (
  symbole text primary key,
  nom text not null default '',
  prix numeric(20, 8) not null,
  veille numeric(20, 8),
  devise text not null default 'EUR',
  place text not null default '',
  type text not null default '',
  maj timestamptz not null default now(),
  source text not null default ''
);
create table if not exists public.cours_hist (
  symbole text not null,
  date date not null,
  close numeric(20, 8) not null,
  primary key (symbole, date)
);
alter table public.cours enable row level security;
alter table public.cours_hist enable row level security;
drop policy if exists read_all on public.cours;
create policy read_all on public.cours for select to authenticated using (true);
drop policy if exists read_all on public.cours_hist;
create policy read_all on public.cours_hist for select to authenticated using (true);
revoke all on public.cours, public.cours_hist from anon, public;
grant select on public.cours, public.cours_hist to authenticated;
