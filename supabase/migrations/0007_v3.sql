-- Comptes existants : nouveaux paramètres et catégories, et une entreprise « Micro-entreprise » qui reprend
-- les clients, factures et opérations de l'ancien module Freelance (rien n'est perdu ni déplacé de façon irréversible)
do $$
declare u record; v_proj uuid; v_debut text;
begin
  for u in select distinct user_id from public.params loop
    perform public.ck_seed_defaults(u.user_id);
    if exists (select 1 from public.params where user_id = u.user_id and cle = 'migr_v3_entreprise') then continue; end if;   -- déjà fait
    insert into public.params (user_id, cle, valeur, libelle) values (u.user_id, 'migr_v3_entreprise', 'Oui', 'Reprise de l''ancien module Freelance dans une entreprise (fait)');
    if exists (select 1 from public.clients where user_id = u.user_id and deleted_at is null)
       or exists (select 1 from public.tx where user_id = u.user_id and activite = 'Entreprise' and deleted_at is null)
       or exists (select 1 from public.invoices where user_id = u.user_id and deleted_at is null) then
      select id into v_proj from public.projets where user_id = u.user_id and type = 'Entreprise' and deleted_at is null order by seq limit 1;
      if v_proj is null then
        select valeur into v_debut from public.params where user_id = u.user_id and cle = 'micro_debut' and deleted_at is null;
        insert into public.projets (user_id, nom, type, part, devise, note, meta)
        values (u.user_id, 'Micro-entreprise', 'Entreprise', 1, 'EUR', 'Reprise de l''ancien module Freelance',
                jsonb_build_object('forme', 'micro_bnc', 'date_debut', coalesce(nullif(v_debut, ''), '2027-01-01')))
        returning id into v_proj;
      end if;
      update public.clients set projet_id = v_proj where user_id = u.user_id and projet_id is null and deleted_at is null;
      update public.invoices set projet_id = v_proj where user_id = u.user_id and projet_id is null and deleted_at is null;
      update public.tx set projet_id = v_proj where user_id = u.user_id and activite = 'Entreprise' and projet_id is null and deleted_at is null;
      update public.recurring set projet_id = v_proj where user_id = u.user_id and activite = 'Entreprise' and projet_id is null and deleted_at is null;
    end if;
  end loop;
end $$;

