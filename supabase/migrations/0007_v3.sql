-- ---------- Devises ----------
alter table public.tx drop constraint if exists tx_devise_check;
alter table public.tx add constraint tx_devise_check check (devise ~ '^[A-Z]{3}$');

create or replace function public.ck_dev(p text) returns text
language sql immutable set search_path = public, pg_temp as $$
  select case when upper(btrim(coalesce(p, ''))) in ('EUR', 'MAD', 'USD', 'GBP', 'CHF') then upper(btrim(p)) else 'EUR' end
$$;

-- Taux « 1 unité de la devise = x EUR » à une date (null = aujourd'hui). MAD : taux réel du jour, sinon paramètre du compte.
-- Autres devises : dernier taux connu dans les 10 jours précédents, sinon le plus récent.
create or replace function public.ck_rate(p_uid uuid, p_cur text, p_date date) returns numeric
language plpgsql stable set search_path = public, pg_temp as $$
declare v numeric;
begin
  if p_cur is null or p_cur = 'EUR' then return 1; end if;
  if p_cur = 'MAD' then
    if p_date is not null then v := public.ck_fx(p_date); end if;
    return coalesce(v, public.ck_param(p_uid, 'taux_mad_eur', 0.093));
  end if;
  if p_date is not null then
    select rate into v from public.fx_rates where pair = p_cur || '/EUR' and date <= p_date and date > p_date - 10 order by date desc limit 1;
  end if;
  if v is null then select rate into v from public.fx_rates where pair = p_cur || '/EUR' order by date desc limit 1; end if;
  return v;
end $$;

