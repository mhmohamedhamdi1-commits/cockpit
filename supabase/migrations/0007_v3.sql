-- Anciennes sauvegardes / classeurs Excel / appareils pas encore à jour : « Freelance » est accepté et converti
create or replace function public.ck_legacy(p_data jsonb) returns jsonb
language plpgsql immutable set search_path = public, pg_temp as $$
declare t text; arr jsonb;
begin
  foreach t in array array['tx', 'categories', 'recurring'] loop
    continue when jsonb_typeof(p_data -> t) is distinct from 'array';
    select coalesce(jsonb_agg(case when r ->> 'activite' = 'Freelance' then r || '{"activite": "Entreprise"}'::jsonb else r end), '[]'::jsonb)
      into arr from jsonb_array_elements(p_data -> t) r;
    p_data := jsonb_set(p_data, array[t], arr);
  end loop;
  return p_data;
end $$;

-- ---------- Normalisation (ck_fix) : devises, entreprise, lots, nouvelles tables ----------
create or replace function public.ck_fix(p_uid uuid, p_tbl text, j jsonb) returns jsonb
language plpgsql set search_path = public, pg_temp as $$
declare d date; m numeric; dev text; tx numeric; nat text; ht numeric; tva numeric; yr text; n int; st text; j2 int; v_proj uuid; v_pad int; v_code text;
begin
  dev := public.ck_dev(j ->> 'devise');
  if p_tbl = 'tx' then
    if j ->> 'activite' = 'Freelance' then j := j || '{"activite": "Entreprise"}'::jsonb; end if;
    d := public.ck_date(j ->> 'date');
    if d is null then perform public.ck_err('date invalide'); end if;
    m := public.ck_num(j ->> 'montant');
    if m is null or m <= 0 then perform public.ck_err('le montant doit être supérieur à 0'); end if;
    if coalesce(j ->> 'activite', '') not in ('Perso', 'Entreprise', 'Immobilier') then perform public.ck_err('activité invalide'); end if;
    if coalesce(j ->> 'sens', '') not in ('Revenu', 'Dépense') then perform public.ck_err('sens invalide'); end if;
    if btrim(coalesce(j ->> 'categorie', '')) = '' then perform public.ck_err('choisis une catégorie'); end if;
    m := round(m, 2);
    tx := public.ck_num(j ->> 'taux');
    if dev = 'EUR' then tx := 1;
    elsif tx is null or tx <= 0 or tx = 1 then
      tx := public.ck_rate(p_uid, dev, d);
      if tx is null then perform public.ck_err('taux de change ' || dev || '/EUR indisponible pour le moment'); end if;
    end if;
    nat := nullif(j ->> 'nature', '');
    if nat is null then
      select c.nature into nat from public.categories c
      where c.user_id = p_uid and c.activite = j ->> 'activite' and c.sens = j ->> 'sens' and c.categorie = btrim(j ->> 'categorie') and c.deleted_at is null;
    end if;
    if coalesce(nat, '') not in ('Courant', 'Investissement', 'Financement') then nat := 'Courant'; end if;
    return j || jsonb_build_object('date', d, 'montant', m, 'devise', dev, 'taux', tx, 'montant_eur', round(m * tx, 2), 'nature', nat,
      'periode', coalesce(nullif(j ->> 'periode', ''), to_char(d, 'YYYY-MM')), 'libelle', btrim(coalesce(j ->> 'libelle', '')),
      'categorie', btrim(j ->> 'categorie'));

  elsif p_tbl = 'invoices' then
    if btrim(coalesce(j ->> 'client', '')) = '' then perform public.ck_err('choisis un client'); end if;
    if length(coalesce(j ->> 'periode', '')) <> 7 then perform public.ck_err('période invalide (AAAA-MM)'); end if;
    ht := coalesce(public.ck_num(j ->> 'ht'), 0);
    if ht = 0 then ht := coalesce(public.ck_num(j ->> 'jours'), 0) * coalesce(public.ck_num(j ->> 'tjm'), 0); end if;
    ht := round(ht, 2);
    tva := coalesce(public.ck_num(j ->> 'tva'), 0);
    st := case when j ->> 'statut' in ('Planifiée', 'Envoyée', 'Payée') then j ->> 'statut' else 'Planifiée' end;
    j := j || jsonb_build_object('devise', dev, 'ht', ht, 'ttc', round(ht * (1 + tva), 2), 'statut', st);
    if coalesce(j ->> 'numero', '') = '' then
      yr := coalesce(left(nullif(j ->> 'emission', ''), 4), left(j ->> 'periode', 4));
      v_proj := public.ck_uuid(j ->> 'projet_id');
      perform pg_advisory_xact_lock(hashtext(p_uid::text || ':invoice-number'));
      select coalesce(max(public.ck_num(substr(numero, length('F-' || yr || '-') + 1))), 0) + 1 into n
      from public.invoices where user_id = p_uid and deleted_at is null and numero like 'F-' || yr || '-%' and projet_id is not distinct from v_proj;
      j := j || jsonb_build_object('numero', format('F-%s-%s', yr, lpad(n::text, 3, '0')));
    end if;
    return j;

  elsif p_tbl = 'snapshots' then
    d := public.ck_date(j ->> 'date');
    if d is null then perform public.ck_err('date invalide'); end if;
    m := coalesce(public.ck_num(j ->> 'solde'), 0);
    tx := public.ck_rate(p_uid, dev, d);
    if tx is null then perform public.ck_err('taux de change ' || dev || '/EUR indisponible pour le moment'); end if;
    return j || jsonb_build_object('date', d, 'devise', dev, 'solde_eur', round(m * tx, 2));

  elsif p_tbl = 'tenants' then
    if btrim(coalesce(j ->> 'nom', '')) = '' or coalesce(j ->> 'lot', '') = '' then perform public.ck_err('nom et lot obligatoires'); end if;
    return j || jsonb_build_object('nom', btrim(j ->> 'nom'));

  elsif p_tbl = 'clients' then
    if btrim(coalesce(j ->> 'nom', '')) = '' then perform public.ck_err('nom du client obligatoire'); end if;
    return j || jsonb_build_object('nom', btrim(j ->> 'nom'), 'devise', dev);

  elsif p_tbl = 'recurring' then
    if j ->> 'activite' = 'Freelance' then j := j || '{"activite": "Entreprise"}'::jsonb; end if;
    if coalesce(public.ck_num(j ->> 'montant'), 0) <= 0 or coalesce(j ->> 'categorie', '') = '' or btrim(coalesce(j ->> 'libelle', '')) = '' then
      perform public.ck_err('libellé, catégorie et montant obligatoires');
    end if;
    j2 := coalesce(public.ck_num(j ->> 'jour'), 1)::int;
    return j || jsonb_build_object('jour', case when j2 between 1 and 31 then j2 else 1 end,
      'actif', case when j ->> 'actif' = 'Non' then 'Non' else 'Oui' end, 'devise', dev, 'libelle', btrim(j ->> 'libelle'));

  elsif p_tbl = 'accounts' then
    if btrim(coalesce(j ->> 'nom', '')) = '' then perform public.ck_err('nom du compte obligatoire'); end if;
    return j || jsonb_build_object('nom', btrim(j ->> 'nom'), 'devise', dev);

  elsif p_tbl = 'lots' then
    if btrim(coalesce(j ->> 'nom', '')) = '' then perform public.ck_err('nom du lot obligatoire'); end if;
    j := j || jsonb_build_object('nom', btrim(j ->> 'nom'));
    if btrim(coalesce(j ->> 'code', '')) = '' then
      -- code incrémental dans le projet : dernier code numérique + 1 (sur 2 chiffres au minimum)
      v_proj := public.ck_uuid(j ->> 'projet_id');
      select coalesce(max(code::int), -1) + 1, greatest(2, coalesce(max(length(code)) filter (where code ~ '^\d+$'), 2))
        into n, v_pad
        from public.lots where user_id = p_uid and deleted_at is null and projet_id is not distinct from v_proj and code ~ '^\d{1,9}$'
         and id is distinct from public.ck_uuid(j ->> 'id');
      v_code := lpad(n::text, v_pad, '0');
      j := j || jsonb_build_object('code', v_code);
    end if;
    return j;

  elsif p_tbl = 'ordres' then
    d := public.ck_date(j ->> 'date');
    if d is null then perform public.ck_err('date invalide'); end if;
    if btrim(coalesce(j ->> 'symbole', '')) = '' then perform public.ck_err('choisis un titre'); end if;
    if coalesce(j ->> 'sens', '') not in ('Achat', 'Vente', 'Dividende') then perform public.ck_err('sens invalide'); end if;
    m := coalesce(public.ck_num(j ->> 'quantite'), 0);
    if j ->> 'sens' in ('Achat', 'Vente') and m <= 0 then perform public.ck_err('la quantité doit être supérieure à 0'); end if;
    if coalesce(public.ck_num(j ->> 'prix'), -1) < 0 then perform public.ck_err('prix invalide'); end if;
    return j || jsonb_build_object('date', d, 'symbole', upper(btrim(j ->> 'symbole')), 'devise', upper(coalesce(nullif(j ->> 'devise', ''), 'EUR')),
      'type', case when j ->> 'type' in ('Action', 'ETF', 'Fonds', 'Obligation', 'Crypto', 'Autre') then j ->> 'type' else 'Action' end,
      'secteur', left(btrim(coalesce(j ->> 'secteur', '')), 60));

  elsif p_tbl = 'rappels' then
    if btrim(coalesce(j ->> 'titre', '')) = '' then perform public.ck_err('titre du rappel obligatoire'); end if;
    d := public.ck_date(j ->> 'date');
    if d is null then perform public.ck_err('date d''échéance invalide'); end if;
    return j || jsonb_build_object('titre', btrim(j ->> 'titre'), 'date', d,
      'frequence', case when j ->> 'frequence' in ('Une fois', 'Mensuel', 'Trimestriel', 'Annuel') then j ->> 'frequence' else 'Une fois' end,
      'avance', greatest(0, coalesce(public.ck_num(j ->> 'avance'), 0)::int),
      'actif', case when j ->> 'actif' = 'Non' then 'Non' else 'Oui' end);

  elsif p_tbl = 'import_lignes' then
    d := public.ck_date(j ->> 'date');
    if d is null then perform public.ck_err('date invalide'); end if;
    m := public.ck_num(j ->> 'montant');
    if m is null or m = 0 then perform public.ck_err('montant nul ou illisible'); end if;
    if btrim(coalesce(j ->> 'hash', '')) = '' then perform public.ck_err('empreinte de la ligne manquante'); end if;
    return j || jsonb_build_object('date', d, 'montant', round(m, 2), 'devise', dev,
      'statut', case when j ->> 'statut' in ('attente', 'valide', 'ignore') then j ->> 'statut' else 'attente' end,
      'activite', case when j ->> 'activite' in ('Perso', 'Entreprise', 'Immobilier') then j ->> 'activite' else 'Perso' end);

  elsif p_tbl = 'objectifs' then
    if btrim(coalesce(j ->> 'nom', '')) = '' then perform public.ck_err('nom de l''objectif obligatoire'); end if;
    if coalesce(public.ck_num(j ->> 'cible'), 0) <= 0 then perform public.ck_err('la cible doit être supérieure à 0'); end if;
    return j || jsonb_build_object('nom', btrim(j ->> 'nom'), 'devise', dev,
      'type', case when j ->> 'type' in ('Patrimoine', 'Épargne', 'Bourse', 'Immobilier', 'Autre') then j ->> 'type' else 'Autre' end,
      'rendement', least(0.5, greatest(-0.5, coalesce(public.ck_num(j ->> 'rendement'), 0))),
      'mensuel', greatest(0, coalesce(public.ck_num(j ->> 'mensuel'), 0)),
      'actif', case when j ->> 'actif' = 'Non' then 'Non' else 'Oui' end);

  elsif p_tbl = 'fiscal' then
    n := coalesce(public.ck_num(j ->> 'annee'), 0)::int;
    if n < 2000 or n > 2100 then perform public.ck_err('année fiscale invalide'); end if;
    if jsonb_typeof(coalesce(j -> 'data', '{}'::jsonb)) <> 'object' then perform public.ck_err('données fiscales invalides'); end if;
    return j || jsonb_build_object('annee', n, 'data', coalesce(j -> 'data', '{}'::jsonb));

  elsif p_tbl = 'declarations' then
    if btrim(coalesce(j ->> 'code', '')) = '' or btrim(coalesce(j ->> 'periode', '')) = '' then perform public.ck_err('déclaration : code et période obligatoires'); end if;
    return j || jsonb_build_object('statut', case when j ->> 'statut' in ('fait', 'paye') then j ->> 'statut' else 'fait' end);
  end if;
  return j;
end $$;

-- ---------- Projets (immobilier ET entreprises) : contrôle du projet_id ----------
create or replace function public.ck_fix_projet(p_uid uuid, p_tbl text, j jsonb) returns jsonb
language plpgsql stable set search_path = public, pg_temp as $$
declare v uuid;
begin
  if p_tbl = 'projets' then
    if btrim(coalesce(j ->> 'nom', '')) = '' then perform public.ck_err('nom du projet obligatoire'); end if;
    if coalesce(j ->> 'type', 'Immobilier') not in ('Immobilier', 'Entreprise') then perform public.ck_err('type de projet invalide'); end if;
    if jsonb_typeof(coalesce(j -> 'meta', '{}'::jsonb)) <> 'object' then perform public.ck_err('paramètres du projet invalides'); end if;
    return j || jsonb_build_object('nom', btrim(j ->> 'nom'), 'part', least(1, greatest(0, coalesce(public.ck_num(j ->> 'part'), 1))),
      'devise', public.ck_dev(j ->> 'devise'), 'type', coalesce(nullif(j ->> 'type', ''), 'Immobilier'), 'meta', coalesce(j -> 'meta', '{}'::jsonb));
  end if;
  if p_tbl not in ('lots', 'tenants', 'tx', 'recurring', 'clients', 'invoices', 'import_lignes', 'declarations') then return j; end if;
  v := public.ck_uuid(j ->> 'projet_id');
  if v is null and p_tbl in ('tenants', 'tx', 'recurring') and coalesce(j ->> 'lot', '') <> '' and (p_tbl = 'tenants' or j ->> 'activite' = 'Immobilier') then
    select projet_id into v from public.lots where user_id = p_uid and nom = j ->> 'lot' and deleted_at is null limit 1;
  end if;
  if v is not null and not exists (select 1 from public.projets where id = v and user_id = p_uid and deleted_at is null) then
    perform public.ck_err('projet introuvable ou accessible en lecture seule');
  end if;
  if p_tbl in ('tx', 'recurring', 'import_lignes') and coalesce(j ->> 'activite', '') not in ('Immobilier', 'Entreprise') then v := null; end if;
  return j || jsonb_build_object('projet_id', v);
end $$;

create or replace function public.ck_table_of(p_entity text) returns text language sql immutable set search_path = public, pg_temp as $$
  select case p_entity when 'tx' then 'tx' when 'lot' then 'lots' when 'tenant' then 'tenants' when 'client' then 'clients'
    when 'invoice' then 'invoices' when 'recurring' then 'recurring' when 'account' then 'accounts'
    when 'snapshot' then 'snapshots' when 'rappel' then 'rappels' when 'projet' then 'projets' when 'ordre' then 'ordres'
